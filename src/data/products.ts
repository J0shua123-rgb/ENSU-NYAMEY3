/**
 * Extracts a numeric Cedis price from user entered custom input (e.g. "50", "GH₵ 50", "20 cedis", "GHc 35.50")
 */
export function parseCustomAmountPrice(customAmount?: string): number | null {
  if (!customAmount) return null;
  const cleaned = customAmount.trim().toLowerCase().replace(/,/g, '');
  // Matches e.g. "ghc 50", "gh₵50", "50 cedis", "50", "$50"
  const match = cleaned.match(/(?:gh[¢c]?\s*|\$\s*)?(\d+(?:\.\d+)?)/i);
  if (match && match[1]) {
    const val = parseFloat(match[1]);
    if (!isNaN(val) && val > 0) {
      return val;
    }
  }
  return null;
}

/**
 * Calculates dynamic price for custom amount entries.
 * Handles:
 * 1. Direct Cedis budget: "GH₵ 50", "50 cedis", "ghc 100", "GH₵ 150"
 * 2. Multipliers / quantities with temporary mock baseline price: "2 packs" @ 45 = 90, "2 kg" @ 65 = 130
 * 3. Default fallback to product.price or parsed budget
 */
export function calculateCustomItemPrice(product: { price: number; isMockPrice?: boolean; isVariablePrice?: boolean }, customAmount?: string): number | null {
  if (!customAmount || customAmount.trim() === '') {
    return product.price > 0 ? product.price : null;
  }
  const cleaned = customAmount.trim().toLowerCase().replace(/,/g, '');

  // 1. Explicit Cedis indicators (e.g. "ghc 50", "gh₵ 100", "50 cedis")
  const explicitCediMatch = cleaned.match(/(?:gh[¢c]|cedi|cedis|\$)\s*(\d+(?:\.\d+)?)/i) ||
                            cleaned.match(/(\d+(?:\.\d+)?)\s*(?:cedi|cedis|ghc|gh¢)/i);
  if (explicitCediMatch && explicitCediMatch[1]) {
    const val = parseFloat(explicitCediMatch[1]);
    if (!isNaN(val) && val > 0) {
      return val;
    }
  }

  // 2. Items with baseline or mock price (e.g. Sausage 45 / pack, Gizzard 65 / kg)
  if (product.price > 0) {
    // Check if user specified quantity of units, e.g. "2 packs", "3 kg", "1.5 kg", "2 packs"
    const unitMatch = cleaned.match(/^(\d+(?:\.\d+)?)\s*(?:pack|packs|kg|kilo|kilos|pcs|pieces|tray|half|full)?/i);
    if (unitMatch && unitMatch[1]) {
      const qty = parseFloat(unitMatch[1]);
      if (!isNaN(qty) && qty > 0) {
        // If it's a small multiplier <= 15, assume it's units of the product (e.g. 2 packs, 1 kg, 3)
        if (qty <= 15) {
          return qty * product.price;
        }
        // If it's a larger number (e.g. 45, 65, 100), assume it's a Cedis budget
        return qty;
      }
    }

    // Direct numeric fallback
    const numericMatch = parseCustomAmountPrice(customAmount);
    if (numericMatch !== null) {
      return numericMatch;
    }
    return product.price;
  }

  // 3. Pure flexible budget products (e.g. Beef, Lobster)
  return parseCustomAmountPrice(customAmount);
}

